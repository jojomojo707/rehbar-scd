#!/usr/bin/env bash
# Deploy the ci overlay to the current kubectl context with every rahbar image pinned to one
# commit SHA (section 6: deploy by SHA, never :latest). Used by ci.yml e2e-eval and cd.yml deploy.
#
# Usage: scripts/ci_deploy.sh <git-sha>
#
# It writes a throwaway overlay, k8s/overlays/ci-sha/ (gitignored), on top of k8s/overlays/ci.
# This has the same effect as `kustomize edit set image` in a copy of the overlay, but needs
# only kubectl's built-in kustomize, not a separate kustomize binary.
set -euo pipefail

sha="${1:?usage: ci_deploy.sh <git-sha>}"
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
overlay="$repo_root/k8s/overlays/ci-sha"
registry="docker.io/majnoon57"

mkdir -p "$overlay"
cat > "$overlay/kustomization.yaml" <<EOF
# Generated by scripts/ci_deploy.sh for commit ${sha}. Do not commit.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../ci
images:
  - name: ${registry}/rahbar-api
    newTag: "${sha}"
  - name: ${registry}/rahbar-ui
    newTag: "${sha}"
  - name: ${registry}/rahbar-indexer
    newTag: "${sha}"
patches:
  - target:
      kind: ConfigMap
      name: rahbar-config
    patch: |-
      - op: replace
        path: /data/IMAGE_TAG
        value: "${sha}"
EOF

echo "Images in the rendered manifests:"
kubectl kustomize "$overlay" | grep -E '^[[:space:]-]+image:' | sort -u

# Fail early if any rahbar image escaped the SHA pin.
if kubectl kustomize "$overlay" | grep -E "image: .*rahbar-(api|ui|indexer)" | grep -v ":${sha}$"; then
  echo "ERROR: an image above is not tagged ${sha}" >&2
  exit 1
fi

# Only ever deploy to a throwaway kind cluster (kind names its contexts kind-<cluster>). This
# stops the script from overwriting a developer's minikube if it is run by hand.
context="$(kubectl config current-context 2>/dev/null || true)"
if [[ "$context" != kind-* ]]; then
  echo "Rendered only: current context '${context}' is not a kind cluster, so nothing was applied."
  exit 0
fi

kubectl apply -k "$overlay"
